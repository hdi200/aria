// Check at execution time so even aggregate tasks cannot produce a debug-signed release.
val validateReleaseSigning by tasks.registering {
    doLast {
        val signing = android.signingConfigs.getByName("release")
        require(signing.storeFile?.isFile == true && !signing.storePassword.isNullOrBlank()
            && !signing.keyAlias.isNullOrBlank() && !signing.keyPassword.isNullOrBlank()) {
            "Release requires a private upload keystore. Run scripts/setup-upload-key.py yourself; see README."
        }
        require(signing.keyAlias != "androiddebugkey" && signing.storeFile?.name != "debug.keystore") {
            "A debug key must never sign a release."
        }
    }
}
tasks.matching { it.name == "preReleaseBuild" }.configureEach { dependsOn(validateReleaseSigning) }

