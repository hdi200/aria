import java.util.Properties

// Local standalone benchmark only. Both switches must agree; never build a bundle.
val ariaPhoneAudit = providers.gradleProperty("ariaPhoneAudit").isPresent
// Each newly built TEST APK can coexist with previous comparisons on the phone.
// The wrapper generates this ID; it never changes the production application ID.
val ariaPhoneAuditId = providers.gradleProperty("ariaPhoneAuditId").orNull
require(ariaPhoneAuditId == null || ariaPhoneAudit) { "TEST identity requires phone audit mode" }
require(ariaPhoneAudit == (System.getenv("ARIA_PHONE_AUDIT") == "1")) {
    "Phone audit requires both -PariaPhoneAudit and ARIA_PHONE_AUDIT=1"
}
if (ariaPhoneAudit) {
    require(ariaPhoneAuditId != null && Regex("t[0-9]{16,24}").matches(ariaPhoneAuditId)) {
        "Phone audit requires a unique -PariaPhoneAuditId generated by the TEST build wrapper"
    }
    require(providers.gradleProperty("ariaSideloadApk").isPresent) { "Phone audit requires sideload sound bank" }
    require(gradle.startParameter.taskNames.none { it.contains("bundle", ignoreCase = true) || it.contains("publish", ignoreCase = true) }) {
        "Performance TEST is APK-only and must never be uploaded"
    }
}

