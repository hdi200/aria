        jvmTarget = org.jetbrains.kotlin.gradle.dsl.JvmTarget.fromTarget(libs.versions.jvm.get().toString())
    }
}

android {
    namespace = group as String
    compileSdk = 36
    compileOptions {
        sourceCompatibility = JavaVersion.toVersion(libs.versions.jvm.get())
        targetCompatibility = JavaVersion.toVersion(libs.versions.jvm.get())
    }
    packaging {
        jniLibs {
            keepDebugSymbols.add("**/*.so")
            pickFirsts.add("**/*.so")
            // this option would compress JNI .so files and reduce overall size for Skip Fuse apps, but cost more at install time
            //useLegacyPackaging = true
            // Aria: Qt loads its plugins from files, so unpack native libraries on install.
            useLegacyPackaging = true
        }
    }

    sourceSets["main"].jniLibs.srcDir(ariaJniLibsDir)
    // Local optimized profiling only. The normal release/upload manifest has no
    // profileable element; do not supply this property when building an upload AAB.
    if (providers.gradleProperty("ariaProfileableRelease").isPresent) {
        sourceSets["release"].manifest.srcFile("src/profileable/AndroidManifest.xml")
    }
    if (ariaPhoneAudit) {
        sourceSets["release"].manifest.srcFile("src/phoneAudit/AndroidManifest.xml")
        defaultConfig.manifestPlaceholders["ariaPhoneAuditLabel"] = "Aria TEST $ariaPhoneAuditId"
        sourceSets["release"].kotlin.srcDir("src/phoneAudit/kotlin")
        sourceSets["release"].res.srcDir("src/phoneAudit/res")
    }
    // Stage shared resources without the sound bank in the base module. Keep ios/
    // paths identical across the base and install-time pack for AssetManager lookup.
    sourceSets["main"].assets.srcDir(baseResources.get().asFile)
    assetPacks += listOf(":soundbank")
    // A local debug APK doesn't carry install-time asset packs, so debug builds also put
    // the sound bank in the base module (same ios/ paths) to keep playback working.
    sourceSets["debug"].assets.srcDir("ios-assets")
    // `-PariaSideloadApk` does the same for a release APK copied straight to a phone.
    // Never upload that build: Play bundles must keep the sound bank in its pack only.
    if (providers.gradleProperty("ariaSideloadApk").isPresent) {
        sourceSets["release"].assets.srcDir("ios-assets")
    }
    // Aria: Material icons for the SF Symbol names the shared views use
    // (scripts/generate-symbols.py).
    sourceSets["main"].assets.srcDir("symbol-assets")
    androidResources {
        // Copied out byte for byte; compressing only slows that down.
        noCompress += listOf("sf2", "otf", "ttf", "jpg", "mp4")
    }

    defaultConfig {
        minSdk = libs.versions.android.sdk.min.get().toInt()
        ndk { abiFilters += listOf("arm64-v8a") }
        targetSdk = 36
        // Local release A/B only; R8 removes frame hashing from normal builds.
        buildConfigField("boolean", "ARIA_VIDEO_AUDIT",
            (providers.environmentVariable("ARIA_VIDEO_AUDIT").orNull == "1").toString())
        buildConfigField("boolean", "ARIA_PHONE_AUDIT", ariaPhoneAudit.toString())
        // skip.tools.skip-build-plugin will automatically use Skip.env properties for:
        // applicationId = ANDROID_APPLICATION_ID ?? PRODUCT_BUNDLE_IDENTIFIER
        // versionCode = CURRENT_PROJECT_VERSION
        // versionName = MARKETING_VERSION
    }

    buildFeatures {
        buildConfig = true
    }

    lint {
        disable.add("Instantiatable")
        disable.add("MissingPermission")
    }

    dependenciesInfo {
        // Disables dependency metadata when building APKs.
        includeInApk = false
        // Disables dependency metadata when building Android App Bundles.
        includeInBundle = false
    }

    // Debug builds remain usable without signing secrets. Release never falls back.
    signingConfigs {
        create("release") {
            val propertiesFile = file("keystore.properties")
            if (propertiesFile.isFile) {
                val properties = Properties().apply { propertiesFile.inputStream().use { load(it) } }
                storeFile = properties.getProperty("storeFile")?.let { file(it) }
                storePassword = properties.getProperty("storePassword")
                keyAlias = properties.getProperty("keyAlias")
                keyPassword = properties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            if (ariaPhoneAudit) {
                applicationIdSuffix = ".performancetest.$ariaPhoneAuditId"
                versionNameSuffix = "-performance-TEST-$ariaPhoneAuditId"
            }
            signingConfig = signingConfigs.findByName("release")
            isMinifyEnabled = true
            isShrinkResources = true
            isDebuggable = false // can be set to true for debugging release build, but needs to be false when uploading to store
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }
}

