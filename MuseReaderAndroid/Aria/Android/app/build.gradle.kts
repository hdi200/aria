// Aria: the shared render core (libaria_engine.so), Qt and Qt's offscreen plugin, from
// ../../scripts/build-engine.sh. Skip ships its own, newer libc++_shared.so.
val ariaNativeLibs = rootProject.file("../../../build-aria-android-arm64/jniLibs")
val ariaJniLibsDir = layout.buildDirectory.dir("ariaJniLibs").get().asFile
val copyAriaNativeLibs by tasks.registering(Copy::class) {
    from(ariaNativeLibs) { exclude("**/libc++_shared.so") }
    into(ariaJniLibsDir)
}
val baseResources = layout.buildDirectory.dir("ariaBaseAssets")
val stageBaseResources by tasks.registering(Sync::class) {
    from("ios-assets") { exclude("**/*.sf2", "**/.DS_Store") }
    into(baseResources)
}
tasks.named("preBuild") { dependsOn(copyAriaNativeLibs, stageBaseResources) }

