#!/usr/bin/env python3
"""Generates AriaEngine/BridgeTypes.swift: Swift versions of the iOS bridge's data classes
(MuseReaderiOS/MuseReaderiOS/Bridge/*.h), with the same names, properties and initializers
the iOS Swift code sees. Input is the Swift interface of those headers:

    xcrun swift-synthesize-interface -module-name MSRBridge -I <dir with the headers and a
      module.modulemap> -target arm64-apple-ios17.0 -sdk "$(xcrun --sdk iphoneos --show-sdk-path)"

Usage: generate-bridge-types.py <interface.swift> <output.swift>
"""
import re
import sys

# Classes with behaviour, written by hand in AriaEngine.
HAND_WRITTEN = {"MSRRenderSession", "MuseScoreRenderCoreBridge", "MSRPlaybackReverb", "MuseScorePackageBridge"}


def split_params(text):
    params, depth, current = [], 0, ""
    for ch in text:
        if ch in "[(<":
            depth += 1
        elif ch in "])>":
            depth -= 1
        if ch == "," and depth == 0:
            params.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        params.append(current.strip())
    return params


def main(source, destination):
    lines = open(source).read().splitlines()
    out = [
        "// Generated by scripts/generate-bridge-types.py from the iOS bridge headers",
        "// (MuseReaderiOS/MuseReaderiOS/Bridge). Do not edit; change the headers and regenerate.",
        "",
        "import Foundation",
        "",
    ]
    index = 0
    while index < len(lines):
        line = lines[index]
        match = re.match(r"open class (\w+) : NSObject \{", line)
        if not match or match.group(1) in HAND_WRITTEN:
            index += 1
            continue
        name = match.group(1)
        # Doc comment lines directly above the class.
        doc = []
        back = index - 1
        while back >= 0 and lines[back].strip().startswith("///"):
            doc.insert(0, lines[back])
            back -= 1
        properties, init_params, pending_doc = [], None, []
        index += 1
        while not lines[index].startswith("}"):
            body = lines[index].strip()
            if body.startswith("///"):
                pending_doc.append("    " + body)
            prop = re.match(r"open var (\w+): (.+?)( \{ get \})?$", body)
            init = re.match(r"public init\((.*)\)$", body)
            if prop:
                properties.append((prop.group(1), prop.group(2), prop.group(3) is None, pending_doc))
                pending_doc = []
            elif init:
                init_params = split_params(init.group(1))
                pending_doc = []
            elif body and not body.startswith("///"):
                pending_doc = []
            index += 1
        out.extend(doc)
        out.append(f"open class {name}: NSObject, @unchecked Sendable {{")
        for prop_name, prop_type, settable, prop_doc in properties:
            out.extend(prop_doc)
            out.append(f"    public {'var' if settable else 'let'} {prop_name}: {prop_type}")
        out.append("")
        assigned = set()
        signature, assignments = [], []
        for param in init_params or []:
            label_part, param_type = param.split(":", 1)
            names = label_part.split()
            internal = names[-1]
            signature.append(f"{label_part}:{param_type}")
            assignments.append(f"        self.{internal} = {internal}")
            assigned.add(internal)
        out.append(f"    public init({', '.join(signature)}) {{")
        out.extend(assignments)
        for prop_name, prop_type, settable, _ in properties:
            if prop_name not in assigned:
                default = "[]" if prop_type.startswith("[") else ("false" if prop_type == "Bool" else "0")
                out.append(f"        self.{prop_name} = {default}")
        out.append("    }")
        out.append("}")
        out.append("")
    open(destination, "w").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
